// ComfyUI accepts more than one request for the same image, so a Studio restart used to leave
// the old worker alive while a new worker queued the entire project again. Keep the guard in the
// worker (rather than its short-lived dispatcher) so it survives exactly that parent restart.
const generationLock = path.join(projectDir, ".image-generation.lock");
let ownsGenerationLock = false;

function processIsAlive(pid) {
  if (!Number.isInteger(pid) || pid < 1) return false;
  try {
    process.kill(pid, 0);
    return true;
  } catch (error) {
    return error.code === "EPERM";
  }
}

async function acquireGenerationLock() {
  for (let attempt = 0; attempt < 2; attempt += 1) {
    try {
      const handle = await fs.open(generationLock, "wx");
      await handle.writeFile(
        `${JSON.stringify(
          {
            pid: process.pid,
            project: flags.project,
            startedAt: new Date().toISOString(),
          },
          null,
          2,
        )}\n`,
      );
      await handle.close();
      ownsGenerationLock = true;
      return;
    } catch (error) {
      if (error.code !== "EEXIST") throw error;
      const owner = await readJson(generationLock).catch(() => null);
      if (processIsAlive(Number(owner?.pid))) {
        throw new Error(
          `Images for "${flags.project}" are already being generated by process ${owner.pid}.`,
        );
      }
      // A hard crash can leave the tiny lock file behind. Remove it only after proving its
      // recorded owner no longer exists, then make one atomic retry.
      await fs.rm(generationLock, { force: true });
    }
  }
  throw new Error(`Could not reserve image generation for "${flags.project}".`);
}

function releaseGenerationLock() {
  if (!ownsGenerationLock) return;
  ownsGenerationLock = false;
  try {
    fsSync.unlinkSync(generationLock);
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
}

