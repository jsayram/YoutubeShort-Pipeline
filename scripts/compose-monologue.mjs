import fs from "node:fs/promises";
import path from "node:path";
import { parseArgs, readJson, videoDir, writeJson } from "./lib.mjs";

// The illustrated emotional monologue composition.
//
// Square artwork centred in a 9:16 frame, over an enlarged blurred copy of itself, under a warm
// wash, vignette and grain, with drifting environmental motion and one-word captions driven by
// real word-level timings.
//
// Unlike compose-slideshow this is caption-bearing by design: the captions are the fastest
// moving element in the format, and they are the reason the word alignment step exists.

const { flags } = parseArgs();
if (!flags.project) throw new Error("Pass --project <slug>.");

const slug = flags.project;
const projectDir = videoDir(slug);
const configPath = path.join(projectDir, "video.json");
const config = await readJson(configPath);
const timingPath = path.join(projectDir, "public", "audio", "narration.timing.json");
const timing = await readJson(timingPath).catch(() => null);

if (!timing) {
  throw new Error(
    `${timingPath} is missing. Build the voice first: npm run story -- --project ${slug}`,
  );
}
if (!Array.isArray(timing.words) || !timing.words.length) {
  throw new Error(
    `No word-level timings in narration.timing.json. Run: npm run align -- --project ${slug}`,
  );
}

const MARKER = "generated by scripts/compose-monologue.mjs";
const compositionPath = path.join(projectDir, "index.html");
const existing = await fs.readFile(compositionPath, "utf8").catch(() => "");
const withoutComments = existing.replace(/<!--[\s\S]*?-->/g, "");
const clipCount = (withoutComments.match(/class="[^"]*\bclip\b[^"]*"/g) ?? []).length;
if (existing && !existing.includes(MARKER) && clipCount > 0 && !flags.force) {
  throw new Error(
    `index.html holds a hand-authored composition (${clipCount} timed clips) and would be ` +
      "overwritten. Pass --force if you really want to replace it.",
  );
}

const generatedDir = path.join(projectDir, "public", "generated");
const onDisk = (await fs.readdir(generatedDir).catch(() => [])).filter((name) =>
  /\.(png|jpe?g|webp)$/i.test(name),
);
const manifest = await readJson(path.join(generatedDir, "manifest.json")).catch(() => null);
const listed = Array.isArray(manifest) ? manifest.map((entry) => path.basename(entry.file)) : [];
const files = listed.filter((name) => onDisk.includes(name));
for (const name of onDisk.sort()) if (!files.includes(name)) files.push(name);

if (!files.length) {
  throw new Error(`No images in public/generated. Run: npm run images -- --project ${slug}`);
}

const width = Number(config.width ?? 1080);
const height = Number(config.height ?? 1920);
const tail = Number(flags.tail ?? 2.5);
const spoken = Number(timing.spokenDuration ?? timing.words.at(-1).end);
const duration = Number((spoken + tail).toFixed(2));

// Scenes are paced independently of the narration lines. The format cuts every few seconds
// regardless of where a sentence ends, which is what keeps it feeling restless.
const DISSOLVE = 0.4;
const sceneCount = files.length;
const sceneLength = duration / sceneCount;

const scenes = files.map((file, index) => {
  const start = Number((index * sceneLength).toFixed(3));
  const end = index === sceneCount - 1 ? duration : Number(((index + 1) * sceneLength).toFixed(3));
  return {
    index,
    id: `scene-${index + 1}`,
    file,
    start,
    // Every third change dissolves; the rest are hard cuts. Dissolving scenes overlap their
    // successor by the dissolve length so both layers are live during the blend.
    dissolve: index > 0 && index % 3 === 0,
    duration: Number((end - start + (index < sceneCount - 1 ? DISSOLVE : 0)).toFixed(3)),
    driftX: index % 2 === 0 ? 1 : -1,
  };
});

// Captions ride one element driven by the timeline clock rather than one clip per word. At 146
// words a clip each would bury the timeline and trip the density lint for no benefit; a single
// driver reading a baked table is also exactly seek-safe.
const words = timing.words.map((word) => ({
  text: String(word.text).replace(/[\\"]/g, ""),
  start: Number(word.start.toFixed(3)),
  end: Number(word.end.toFixed(3)),
}));

await fs.writeFile(compositionPath, renderHtml());

config.duration = duration;
await writeJson(configPath, config);
timing.videoDuration = duration;
await writeJson(timingPath, timing);

console.log(`Wrote ${path.relative(projectDir, compositionPath)}`);
console.log(
  `${scenes.length} scenes over ${duration}s (${sceneLength.toFixed(1)}s each), ` +
    `${words.length} caption words, ${scenes.filter((s) => s.dissolve).length} dissolves.`,
);
if (sceneCount < 9 || sceneCount > 12) {
  console.log(`Note: ${sceneCount} scenes. The format wants 9 to 12 for a 60s piece.`);
}

function renderHtml() {
  const sceneMarkup = scenes
    .map(
      (scene) => `      <div
        id="${scene.id}"
        class="clip scene"
        data-start="${scene.start}"
        data-duration="${scene.duration}"
        data-track-index="${scene.index + 1}"
      >
        <div id="${scene.id}-inner" class="scene-inner" data-layout-allow-overflow="true">
          <div
            class="fill"
            style="background-image: url('public/generated/${scene.file}')"
          ></div>
          <div class="art-wrap"><img class="art" src="public/generated/${scene.file}" alt="" /></div>
        </div>
      </div>`,
    )
    .join("\n");

  const sceneData = scenes
    .map(
      (scene) =>
        `        { id: "${scene.id}", start: ${scene.start}, duration: ${scene.duration}, ` +
        `dissolve: ${scene.dissolve}, driftX: ${scene.driftX} }`,
    )
    .join(",\n");

  const wordData = words
    .map((word) => `        { t: "${word.text}", s: ${word.start}, e: ${word.end} }`)
    .join(",\n");

  const overlayTrack = scenes.length + 1;

  return `<!doctype html>
<html lang="en" data-resolution="portrait">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=${width}, height=${height}" />
    <title>${escapeHtml(config.title ?? slug)}</title>
    <!-- ${MARKER} — re-running the compose step replaces this file. -->
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
    <style>
      * {
        margin: 0;
        padding: 0;
        box-sizing: border-box;
      }
      html,
      body {
        width: ${width}px;
        height: ${height}px;
        overflow: hidden;
        background: #0a0908;
      }
      #root {
        position: relative;
        width: ${width}px;
        height: ${height}px;
        overflow: hidden;
      }
      #bg-fill {
        position: absolute;
        inset: 0;
        background: #0a0908;
      }

      .scene {
        position: absolute;
        inset: 0;
        overflow: hidden;
      }
      /* Camera and cross-fade ride this wrapper. The framework owns .clip visibility. */
      .scene-inner {
        position: absolute;
        inset: 0;
        will-change: transform, opacity;
      }

      /* The enlarged blurred copy that fills the space above and below the square. Painted as a
         background rather than a second <img> of the same file: two identical img entries at the
         same start and duration get discovered twice during compilation. The blur is a static
         CSS value, never animated, since animating filter is not seek-safe. */
      .fill {
        position: absolute;
        left: 50%;
        top: 50%;
        width: ${Math.round(width * 1.6)}px;
        height: ${Math.round(width * 1.6)}px;
        transform: translate(-50%, -50%);
        background-size: cover;
        background-position: center;
        filter: blur(48px) saturate(0.75) brightness(0.55);
      }

      /* The sharp square sits centred, its own width edge to edge. */
      .art-wrap {
        position: absolute;
        left: 0;
        top: 50%;
        width: ${width}px;
        height: ${width}px;
        margin-top: -${Math.round(width / 2)}px;
        overflow: hidden;
      }
      .art {
        width: 100%;
        height: 100%;
        object-fit: cover;
        display: block;
      }

      /* Warm wash, vignette and grain sit above every scene and below the captions. */
      .overlay {
        position: absolute;
        inset: 0;
        pointer-events: none;
      }
      #wash {
        background: linear-gradient(
          180deg,
          rgba(120, 82, 42, 0.22) 0%,
          rgba(60, 52, 44, 0.1) 45%,
          rgba(20, 24, 26, 0.3) 100%
        );
        mix-blend-mode: multiply;
      }
      #vignette {
        background: radial-gradient(
          760px 1180px at 50% 48%,
          rgba(0, 0, 0, 0) 52%,
          rgba(0, 0, 0, 0.72) 100%
        );
      }
      /* Grain as a repeating SVG noise tile: deterministic, no external asset. */
      #grain {
        opacity: 0.09;
        background-image: url("data:image/svg+xml;utf8,\
<svg xmlns='http://www.w3.org/2000/svg' width='160' height='160'>\
<filter id='n'><feTurbulence type='fractalNoise' baseFrequency='0.85' numOctaves='3'/></filter>\
<rect width='160' height='160' filter='url(%23n)'/></svg>");
        background-size: 320px 320px;
      }

      /* Environmental drift: a fixed pool of motes, positioned from their index. */
      .mote {
        position: absolute;
        border-radius: 50%;
        background: rgba(233, 217, 187, 0.5);
        will-change: transform;
      }

      /* Captions: one word at a time, heavy outline so they hold over any artwork. */
      #caption {
        position: absolute;
        inset: 0;
        display: flex;
        align-items: center;
        justify-content: center;
        padding: 0 90px;
      }
      #caption-word {
        display: block;
        /* Only fonts the renderer can resolve on its own. Naming a face it cannot fetch is a
           lint error, and silently falls back to the wrong typography in the render. */
        font-family: "Nunito", "Inter", sans-serif;
        font-size: 84px;
        font-weight: 800;
        letter-spacing: 0.01em;
        text-align: center;
        color: #ffffff;
        -webkit-text-stroke: 10px #0a0908;
        paint-order: stroke fill;
        text-shadow:
          0 4px 0 rgba(10, 9, 8, 0.9),
          0 0 34px rgba(0, 0, 0, 0.6);
        will-change: transform, opacity;
      }
    </style>
  </head>
  <body>
    <div
      id="root"
      data-composition-id="main"
      data-start="0"
      data-duration="${duration}"
      data-width="${width}"
      data-height="${height}"
    >
      <div id="bg" class="clip" data-start="0" data-duration="${duration}" data-track-index="0">
        <div id="bg-fill"></div>
      </div>

${sceneMarkup}

      <div
        id="atmosphere"
        class="clip"
        data-start="0"
        data-duration="${duration}"
        data-track-index="${overlayTrack}"
      >
        <div id="motes" class="overlay"></div>
        <div id="wash" class="overlay"></div>
        <div id="vignette" class="overlay"></div>
        <div id="grain" class="overlay"></div>
      </div>

      <div
        id="caption"
        class="clip"
        data-start="0"
        data-duration="${duration}"
        data-track-index="${overlayTrack + 1}"
      >
        <span id="caption-word"></span>
      </div>

      <audio
        id="vo"
        src="public/audio/narration.wav"
        data-start="0"
        data-duration="${Number(Math.min(spoken, duration).toFixed(3))}"
        data-track-index="${overlayTrack + 2}"
        data-volume="1"
      ></audio>
    </div>

    <script>
      window.__timelines = window.__timelines || {};
      const tl = gsap.timeline({ paused: true });

      const DISSOLVE = ${DISSOLVE};
      const DURATION = ${duration};

      const scenes = [
${sceneData}
      ];

      /* Camera: a restrained push with a small opposing drift each scene, so consecutive
         images never travel the same way. */
      for (const scene of scenes) {
        const inner = "#" + scene.id + "-inner";
        tl.fromTo(
          inner,
          { scale: 1.02, x: -10 * scene.driftX },
          {
            scale: 1.08,
            x: 10 * scene.driftX,
            duration: scene.duration,
            ease: "none",
            transformOrigin: "50% 50%",
            immediateRender: false,
          },
          scene.start,
        );

        // Hard cut by default. A dissolving scene fades its wrapper up while the previous one
        // is still live underneath.
        if (scene.dissolve) {
          tl.fromTo(
            inner,
            { opacity: 0 },
            { opacity: 1, duration: DISSOLVE, ease: "none", immediateRender: false },
            scene.start,
          );
        }
      }

      /* Environmental motion: a fixed pool of motes drifting upward. Positions and speeds come
         from the index, never from Math.random, so every render is identical. */
      const MOTES = 18;
      const moteHost = document.getElementById("motes");
      for (let i = 0; i < MOTES; i += 1) {
        const size = 3 + ((i * 7) % 5);
        const left = ((i * 137) % 100);
        const top = ((i * 61) % 100);
        const mote = document.createElement("div");
        mote.className = "mote";
        mote.style.width = size + "px";
        mote.style.height = size + "px";
        mote.style.left = left + "%";
        mote.style.top = top + "%";
        mote.style.opacity = String(0.18 + ((i % 5) * 0.06));
        moteHost.append(mote);

        const rise = 90 + ((i * 23) % 70);
        const sway = 14 + ((i * 11) % 18);
        tl.fromTo(
          mote,
          { y: rise, x: -sway },
          { y: -rise, x: sway, duration: DURATION, ease: "none", immediateRender: false },
          0,
        );
      }

      /* Captions. One element, one driver. The active word is a pure function of timeline time,
         so scrubbing backwards lands on exactly the word that was showing. Text is written only
         when the index changes; the pop is computed from time within the word. */
      const words = [
${wordData}
      ];

      const captionEl = document.getElementById("caption-word");
      const POP = 0.1;
      let shownIndex = -1;

      function wordAt(time) {
        let lo = 0;
        let hi = words.length - 1;
        let found = -1;
        while (lo <= hi) {
          const mid = (lo + hi) >> 1;
          if (words[mid].s <= time) {
            found = mid;
            lo = mid + 1;
          } else {
            hi = mid - 1;
          }
        }
        // A word holds until the next one starts, so there is never a gap mid-sentence.
        if (found < 0) return -1;
        const isLast = found === words.length - 1;
        const until = isLast ? words[found].e + 0.6 : words[found + 1].s;
        return time < until ? found : -1;
      }

      tl.fromTo(
        { p: 0 },
        { p: 0 },
        {
          p: 1,
          duration: DURATION,
          ease: "none",
          immediateRender: false,
          onUpdate: () => {
            const time = tl.time();
            const index = wordAt(time);
            if (index !== shownIndex) {
              shownIndex = index;
              captionEl.textContent = index < 0 ? "" : words[index].t;
            }
            if (index < 0) {
              gsap.set(captionEl, { opacity: 0 });
              return;
            }
            const into = time - words[index].s;
            const progress = into < POP ? into / POP : 1;
            gsap.set(captionEl, {
              opacity: Math.min(1, progress * 2.5),
              scale: 0.94 + 0.06 * progress,
              transformOrigin: "50% 50%",
            });
          },
        },
        0,
      );

      window.__timelines["main"] = tl;
    </script>
  </body>
</html>
`;
}

function escapeHtml(value) {
  return String(value).replace(
    /[&<>"']/g,
    (character) =>
      ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[character],
  );
}
