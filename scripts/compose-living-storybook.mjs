import fs from "node:fs/promises";
import path from "node:path";
import { parseArgs, readJson, videoDir, writeJson } from "./lib.mjs";

// A motion-enabled companion to the original storybook provider.
//
// It uses the same square, hand-painted artwork but adds a restrained living-illustration
// treatment: a localized subject layer that subtly breathes and sways, a single moving light
// sweep, drifting haze and deterministic motes. The motion is deliberately small. It should
// register as life inside the frame without making the painting look rubbery.

const { flags } = parseArgs();
if (!flags.project) throw new Error("Pass --project <slug>.");

const slug = flags.project;
const projectDir = videoDir(slug);
const configPath = path.join(projectDir, "video.json");
const config = await readJson(configPath);
const timingPath = path.join(projectDir, "public", "audio", "narration.timing.json");
const timing = await readJson(timingPath).catch(() => null);

if (!timing) {
  throw new Error(
    `${timingPath} is missing. Build the voice first: npm run story -- --project ${slug}`,
  );
}

const MARKER = "generated by scripts/compose-living-storybook.mjs";
const compositionPath = path.join(projectDir, "index.html");
const existing = await fs.readFile(compositionPath, "utf8").catch(() => "");
const generated =
  existing.includes(MARKER) || existing.includes("generated by scripts/compose-slideshow.mjs");
const withoutComments = existing.replace(/<!--[\s\S]*?-->/g, "");
const clipCount = (withoutComments.match(/class="[^"]*\bclip\b[^"]*"/g) ?? []).length;
const scaffold = clipCount === 0;

if (existing && !generated && !scaffold && !flags.force) {
  throw new Error(
    `index.html holds a hand-authored composition (${clipCount} timed clips) and would be ` +
      "overwritten. Pass --force if you really want to replace it.",
  );
}

const generatedDir = path.join(projectDir, "public", "generated");
const manifest = await readJson(path.join(generatedDir, "manifest.json")).catch(() => null);
const onDisk = new Set(
  (await fs.readdir(generatedDir).catch(() => [])).filter((name) =>
    /\.(png|jpe?g|webp)$/i.test(name),
  ),
);
const listed = Array.isArray(manifest) ? manifest.map((entry) => path.basename(entry.file)) : [];
const files = listed.filter((name) => onDisk.has(name));
for (const name of [...onDisk].sort()) if (!files.includes(name)) files.push(name);
const missing = listed.filter((name) => !onDisk.has(name));

if (!files.length) {
  throw new Error(
    `No images in ${path.relative(projectDir, generatedDir)}. ` +
      `Generate them first: npm run images -- --project ${slug}`,
  );
}

const lines = timing.lines ?? [];
if (!lines.length) throw new Error("The timing file has no lines.");

const tail = Number(flags.tail ?? (timing.finalHoldMs ?? config.voicebox?.finalHoldMs ?? 3000) / 1000);
const narrationDuration = Number(
  timing.narrationDuration ?? timing.spokenDuration ?? lines.at(-1).end,
);
const duration = Number((narrationDuration + tail).toFixed(3));
const width = Number(config.width ?? 1080);
const height = Number(config.height ?? 1920);
const FADE = 0.5;

const scenes = lines.map((line, index) => {
  const paced = Number.isFinite(Number(line.imageStart)) && Number.isFinite(Number(line.imageEnd));
  const start = paced ? Number(line.imageStart) : index === 0 ? 0 : Number(line.start);
  const nextStart =
    index === lines.length - 1
      ? duration
      : Number(lines[index + 1].speechStart ?? lines[index + 1].start);
  const end = paced
    ? index === lines.length - 1
      ? duration
      : Number(line.imageEnd)
    : index === lines.length - 1
      ? duration
      : nextStart + FADE;
  const sceneDuration = round(end - start);
  const fadeDuration =
    index === 0
      ? 0
      : paced
        ? Math.max(0, Number(line.transitionEnd) - Number(line.transitionStart))
        : FADE;
  return {
    index,
    id: `scene-${index + 1}`,
    file: files[index % files.length],
    start: round(start),
    duration: sceneDuration,
    fadeDuration: round(fadeDuration),
    driftX: index % 2 === 0 ? 1 : -1,
    driftY: index % 3 === 0 ? -1 : 1,
    lifeCycles: Math.max(1, round(sceneDuration / (2.8 + (index % 3) * 0.25))),
    lifeAmp: round(0.006 + (index % 3) * 0.001),
    swayAmp: 1.4 + (index % 2) * 0.5,
    glowX: 47 + ((index * 11) % 9),
    glowY: 59 + ((index * 7) % 12),
  };
});

const vendored = await fs
  .access(path.join(projectDir, "public", "vendor", "gsap.min.js"))
  .then(() => true, () => false);
const gsapSrc = vendored
  ? "public/vendor/gsap.min.js"
  : "https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js";

await fs.writeFile(compositionPath, renderHtml());
await writeJson(path.join(projectDir, "index.motion.json"), {
  duration,
  maxStaticSec: 1.4,
  assertions: [
    {
      kind: "keepsMoving",
      withinSelector: "#root",
      maxStaticSec: 1.4,
    },
  ],
});

config.duration = duration;
await writeJson(configPath, config);
timing.videoDuration = duration;
if (timing.lines?.at(-1)?.imageEnd !== undefined) {
  timing.lines.at(-1).imageEnd = duration;
  timing.lines.at(-1).pauseEnd = duration;
}
await writeJson(timingPath, timing);

console.log(`Wrote ${path.relative(projectDir, compositionPath)}`);
console.log(
  `${scenes.length} living scene(s) over ${duration}s (${narrationDuration.toFixed(2)}s narration + ` +
    `${tail}s hold), ${files.length} image(s)${vendored ? ", local GSAP" : ""}.`,
);
console.log("Motion: localized character life · moving light · haze · deterministic motes.");
if (missing.length) {
  console.log(`Note: ${missing.length} manifest entr(ies) have no file on disk: ${missing.join(", ")}`);
}
if (files.length < lines.length) {
  console.log(`Note: ${files.length} image(s) for ${lines.length} line(s) — stills repeat.`);
}

function round(value) {
  return Number(Number(value).toFixed(3));
}

function moteMarkup(scene) {
  return Array.from({ length: 12 }, (_, index) => {
    const size = 2 + ((scene.index * 5 + index * 7) % 5);
    const left = 7 + ((scene.index * 19 + index * 31) % 86);
    const top = 8 + ((scene.index * 23 + index * 17) % 82);
    const opacity = (0.18 + ((index + scene.index) % 5) * 0.055).toFixed(3);
    return (
      `            <i class="story-mote" data-mote="${index}" ` +
      `style="left:${left}%;top:${top}%;width:${size}px;height:${size}px;opacity:${opacity}"></i>`
    );
  }).join("\n");
}

function renderHtml() {
  const sceneMarkup = scenes
    .map(
      (scene) => `      <div
        id="${scene.id}"
        class="clip scene"
        data-start="${scene.start}"
        data-duration="${scene.duration}"
        data-track-index="${scene.index + 1}"
      >
        <div id="${scene.id}-inner" class="scene-inner" data-layout-allow-overflow="true">
          <div class="fill" style="background-image:url('public/generated/${scene.file}')"></div>
          <div class="art-frame" data-layout-allow-overflow="true">
            <img class="still" src="public/generated/${scene.file}" alt="" />
            <div
              id="${scene.id}-life"
              class="subject-life"
              style="background-image:url('public/generated/${scene.file}')"
            ></div>
            <div
              id="${scene.id}-glow"
              class="story-glow"
              style="--glow-x:${scene.glowX}%;--glow-y:${scene.glowY}%"
            ></div>
            <div id="${scene.id}-sweep" class="light-sweep"></div>
            <div id="${scene.id}-mist" class="story-mist"></div>
            <div id="${scene.id}-motes" class="mote-field">
${moteMarkup(scene)}
            </div>
          </div>
        </div>
      </div>`,
    )
    .join("\n");

  const sceneData = scenes
    .map(
      (scene) =>
        `        { id: "${scene.id}", start: ${scene.start}, duration: ${scene.duration}, ` +
        `fadeDuration: ${scene.fadeDuration}, driftX: ${scene.driftX}, ` +
        `driftY: ${scene.driftY}, lifeCycles: ${scene.lifeCycles}, ` +
        `lifeAmp: ${scene.lifeAmp}, swayAmp: ${scene.swayAmp} }`,
    )
    .join(",\n");

  return `<!doctype html>
<html lang="en" data-resolution="portrait">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=${width}, height=${height}" />
    <title>${escapeHtml(config.title ?? slug)}</title>
    <!-- ${MARKER} — re-running the compose step replaces this file. -->
    <script src="${gsapSrc}"></script>
    <style>
      * { margin: 0; padding: 0; box-sizing: border-box; }
      html, body {
        width: ${width}px;
        height: ${height}px;
        overflow: hidden;
        background: #090806;
      }
      #root {
        position: relative;
        width: ${width}px;
        height: ${height}px;
        overflow: hidden;
      }
      #bg-fill {
        position: absolute;
        inset: 0;
        background: #090806;
      }
      .scene {
        position: absolute;
        inset: 0;
        overflow: hidden;
      }
      .scene-inner {
        position: absolute;
        inset: 0;
        will-change: transform, opacity;
      }
      .fill {
        position: absolute;
        left: 50%;
        top: 50%;
        width: ${Math.round(width * 1.72)}px;
        height: ${Math.round(height * 1.12)}px;
        transform: translate(-50%, -50%);
        background-size: cover;
        background-position: center;
        opacity: 0.38;
      }
      .art-frame {
        position: absolute;
        left: 0;
        top: 50%;
        width: ${width}px;
        height: ${width}px;
        margin-top: -${Math.round(width / 2)}px;
        overflow: hidden;
        isolation: isolate;
        box-shadow: 0 44px 110px rgba(0, 0, 0, 0.48);
      }
      .still {
        position: absolute;
        inset: 0;
        display: block;
        width: 100%;
        height: 100%;
        object-fit: cover;
      }

      /* A second rendering of the same art, but as CSS paint rather than a second media node.
         The feathered lower-centre mask isolates the motion-ready character placement requested
         by this provider's prompt. Its amplitude is tiny to avoid a rubber-sheet effect. */
      .subject-life {
        position: absolute;
        inset: 0;
        background-size: cover;
        background-position: center;
        opacity: 0.62;
        -webkit-mask-image: radial-gradient(
          ellipse 32% 43% at 50% 69%,
          #000 0%,
          rgba(0, 0, 0, 0.92) 46%,
          rgba(0, 0, 0, 0.38) 74%,
          transparent 100%
        );
        mask-image: radial-gradient(
          ellipse 32% 43% at 50% 69%,
          #000 0%,
          rgba(0, 0, 0, 0.92) 46%,
          rgba(0, 0, 0, 0.38) 74%,
          transparent 100%
        );
        transform-origin: 50% 88%;
        will-change: transform;
      }
      .story-glow {
        position: absolute;
        inset: -12%;
        background: radial-gradient(
          circle at var(--glow-x) var(--glow-y),
          rgba(255, 224, 157, 0.42) 0%,
          rgba(203, 147, 70, 0.16) 17%,
          transparent 48%
        );
        mix-blend-mode: screen;
        opacity: 0;
        will-change: transform, opacity;
      }
      .light-sweep {
        position: absolute;
        left: -44%;
        top: -18%;
        width: 32%;
        height: 140%;
        background: linear-gradient(
          90deg,
          transparent 0%,
          rgba(255, 230, 176, 0.03) 22%,
          rgba(255, 238, 194, 0.18) 50%,
          rgba(255, 230, 176, 0.03) 78%,
          transparent 100%
        );
        transform: rotate(11deg);
        mix-blend-mode: screen;
        opacity: 0;
        will-change: transform, opacity;
      }
      .story-mist {
        position: absolute;
        left: -15%;
        bottom: -12%;
        width: 130%;
        height: 48%;
        background:
          linear-gradient(164deg, transparent 12%, rgba(217, 196, 156, 0.12) 47%, transparent 72%),
          linear-gradient(18deg, transparent 24%, rgba(115, 126, 113, 0.1) 58%, transparent 84%);
        mix-blend-mode: screen;
        opacity: 0.16;
        will-change: transform, opacity;
      }
      .mote-field {
        position: absolute;
        inset: 0;
        overflow: hidden;
        pointer-events: none;
      }
      .story-mote {
        position: absolute;
        display: block;
        border-radius: 50%;
        background: rgba(255, 225, 164, 0.88);
        box-shadow: 0 0 12px rgba(255, 205, 112, 0.42);
        will-change: transform, opacity;
      }
      #wash, #vignette, #grain {
        position: absolute;
        inset: 0;
        pointer-events: none;
      }
      #wash {
        background: linear-gradient(
          180deg,
          rgba(118, 76, 29, 0.16),
          rgba(39, 35, 30, 0.04) 45%,
          rgba(16, 18, 17, 0.28)
        );
        mix-blend-mode: multiply;
      }
      #vignette {
        background: radial-gradient(
          760px 1180px at 50% 49%,
          transparent 51%,
          rgba(0, 0, 0, 0.7) 100%
        );
      }
      #grain {
        opacity: 0.075;
        background-image: url("data:image/svg+xml;utf8,\
<svg xmlns='http://www.w3.org/2000/svg' width='160' height='160'>\
<filter id='n'><feTurbulence type='fractalNoise' baseFrequency='0.82' numOctaves='3'/></filter>\
<rect width='160' height='160' filter='url(%23n)'/></svg>");
        background-size: 320px 320px;
      }
    </style>
  </head>
  <body>
    <div
      id="root"
      data-composition-id="main"
      data-start="0"
      data-duration="${duration}"
      data-width="${width}"
      data-height="${height}"
    >
      <div id="bg" class="clip" data-start="0" data-duration="${duration}" data-track-index="0">
        <div id="bg-fill"></div>
      </div>

${sceneMarkup}

      <div
        id="finish"
        class="clip"
        data-start="0"
        data-duration="${duration}"
        data-track-index="${scenes.length + 1}"
      >
        <div id="wash"></div>
        <div id="vignette"></div>
        <div id="grain"></div>
      </div>

      <audio
        id="vo"
        src="public/audio/narration.wav"
        data-start="0"
        data-duration="${round(Math.min(narrationDuration, duration))}"
        data-track-index="${scenes.length + 2}"
        data-volume="1"
      ></audio>
    </div>

    <script>
      window.__timelines = window.__timelines || {};
      const tl = gsap.timeline({ paused: true });
      const FADE = ${FADE};
      const ART_WIDTH = ${width};

      const scenes = [
${sceneData}
      ];

      for (const scene of scenes) {
        const inner = "#" + scene.id + "-inner";
        const life = document.getElementById(scene.id + "-life");
        const glow = document.getElementById(scene.id + "-glow");
        const sweep = "#" + scene.id + "-sweep";
        const mist = "#" + scene.id + "-mist";

        // The camera is restrained. The new provider earns its name from the internal layers,
        // not from a more aggressive Ken Burns move.
        tl.fromTo(
          inner,
          { scale: 1.015, x: -8 * scene.driftX, y: -6 * scene.driftY },
          {
            scale: 1.058,
            x: 8 * scene.driftX,
            y: 6 * scene.driftY,
            duration: scene.duration,
            ease: "none",
            transformOrigin: "50% 50%",
            immediateRender: false,
          },
          scene.start,
        );
        if (scene.fadeDuration > 0) {
          tl.fromTo(
            inner,
            { opacity: 0 },
            {
              opacity: 1,
              duration: scene.fadeDuration,
              ease: "none",
              immediateRender: false,
            },
            scene.start,
          );
        }

        // Localized character life. Every value is a pure function of phase, starts at rest,
        // and settles during the last fifth of the scene so the transition does not catch it
        // mid-breath.
        const lifePhase = { p: 0 };
        tl.fromTo(
          lifePhase,
          { p: 0 },
          {
            p: Math.PI * 2 * scene.lifeCycles,
            duration: scene.duration,
            ease: "none",
            immediateRender: false,
            onUpdate: () => {
              const progress = lifePhase.p / (Math.PI * 2 * scene.lifeCycles);
              const envelope = progress < 0.8 ? 1 : Math.max(0, (1 - progress) / 0.2);
              const breath = Math.sin(lifePhase.p) * envelope;
              const sway = Math.sin(lifePhase.p * 0.67) * envelope;
              life.style.transform =
                "translate3d(" + (sway * scene.swayAmp) + "px," +
                (-breath * 2.2) + "px,0) rotate(" + (sway * 0.16) + "deg) scaleY(" +
                (1 + breath * scene.lifeAmp) + ")";
            },
          },
          scene.start,
        );

        // One bloom and one bounded glow hold. The peak remains below the 0.45 ceiling.
        const bloomDuration = Math.min(1.05, Math.max(0.45, scene.duration * 0.22));
        tl.fromTo(
          glow,
          { opacity: 0.04, scale: 0.94 },
          {
            opacity: 0.24,
            scale: 1.04,
            duration: bloomDuration,
            ease: "power2.out",
            immediateRender: false,
          },
          scene.start,
        );
        const glowDuration = Math.max(0.1, scene.duration - bloomDuration);
        const glowPhase = { p: 0 };
        tl.fromTo(
          glowPhase,
          { p: 0 },
          {
            p: Math.PI * 2 * Math.max(1, glowDuration / 3.2),
            duration: glowDuration,
            ease: "none",
            immediateRender: false,
            onUpdate: () => {
              const pulse = Math.sin(glowPhase.p);
              glow.style.opacity = String(0.21 + pulse * 0.025);
              glow.style.transform = "scale(" + (1.04 + pulse * 0.014) + ")";
            },
          },
          scene.start + bloomDuration,
        );

        // A single soft light pass makes the painting visibly time-based without becoming a
        // looping shimmer.
        const sweepStart = scene.start + Math.min(0.8, scene.duration * 0.2);
        const sweepDuration = Math.min(1.45, Math.max(0.65, scene.duration * 0.32));
        tl.fromTo(
          sweep,
          { x: -ART_WIDTH * 0.12, opacity: 0 },
          {
            x: ART_WIDTH * 1.55,
            opacity: 0.19,
            duration: sweepDuration,
            ease: "none",
            immediateRender: false,
          },
          sweepStart,
        );
        tl.to(
          sweep,
          { opacity: 0, duration: Math.min(0.34, sweepDuration * 0.24), ease: "power1.in" },
          sweepStart + sweepDuration * 0.76,
        );

        tl.fromTo(
          mist,
          { x: -24 * scene.driftX, opacity: 0.1 },
          {
            x: 30 * scene.driftX,
            opacity: 0.2,
            duration: scene.duration,
            ease: "none",
            immediateRender: false,
          },
          scene.start,
        );

        const motes = document.querySelectorAll("#" + scene.id + "-motes .story-mote");
        motes.forEach((mote, index) => {
          const direction = (index + scene.index) % 2 === 0 ? 1 : -1;
          const rise = 58 + ((index * 19 + scene.index * 11) % 68);
          const travel = 8 + ((index * 13 + scene.index * 7) % 22);
          tl.fromTo(
            mote,
            { x: -travel * direction, y: rise, opacity: 0.08 },
            {
              x: travel * direction,
              y: -rise,
              opacity: 0.54,
              duration: scene.duration,
              ease: "none",
              immediateRender: false,
            },
            scene.start,
          );
        });
      }

      window.__timelines["main"] = tl;
    </script>
  </body>
</html>
`;
}

function escapeHtml(value) {
  return String(value).replace(
    /[&<>"']/g,
    (character) =>
      ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[character],
  );
}
